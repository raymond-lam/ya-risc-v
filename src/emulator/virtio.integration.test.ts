/**
 * Whole-machine virtio integration: boots the real `Emulator` (hart + timer +
 * terminal workers over one SharedArrayBuffer) with a real temp raw disk file
 * and lets a guest negotiate virtio-mmio, submit one block read through the
 * split virtqueue, verify the data, and power off through syscon. The second
 * guest consumes the completion as a machine external interrupt from PLIC
 * source 1. Image discipline per AGENTS.md; shared boot/teardown harness in
 * `#test/integration-harness`.
 */

